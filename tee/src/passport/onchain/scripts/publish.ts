// publish — publish helix_passport to Sui testnet with LANE_B_DEPLOYER and set the attestor key,
// executed through Tatum (Sui JSON-RPC is retired; the CLI cannot execute).
//
//   (cd ../contracts-passport && sui move build --dump-bytecode-as-base64 > /path/build.json)
//   node --env-file=../.env src/passport/onchain/scripts/publish.ts publish --build /path/build.json [--execute]
//   node --env-file=../.env src/passport/onchain/scripts/publish.ts set-attestor --package 0x… --registry 0x… --cap 0x… [--execute]
//
// Without --execute it only simulates. On a successful publish it writes contracts-passport/Published.toml.

import { readFileSync, writeFileSync } from 'node:fs';
import { Transaction } from '@mysten/sui/transactions';
import { suiClient, recordExecution } from '../../../shared/tatum.ts';
import { keypairFrom, attestorKeypair } from '../attestation.ts';

const args = process.argv.slice(2);
const step = args[0];
const opt = (k: string) => { const i = args.indexOf(`--${k}`); return i >= 0 ? args[i + 1] : undefined; };
const execute = args.includes('--execute');

const deployerKey = process.env.LANE_B_DEPLOYER?.trim();
if (!deployerKey) throw new Error('LANE_B_DEPLOYER not set');
const kp = keypairFrom(deployerKey);
const sender = kp.toSuiAddress();
const client: any = suiClient('testnet');

const unwrap = (r: any) => r?.Transaction ?? r?.FailedTransaction ?? r?.transaction ?? r;

async function run(tx: Transaction, label: string) {
  tx.setSender(sender);
  const bytes = await tx.build({ client });
  const sim = unwrap(await client.simulateTransaction({ transaction: bytes, include: { effects: true } }));
  const eff = sim?.effects;
  console.log(JSON.stringify({ step: label, sender, simulate: eff?.status, gasUsed: eff?.gasUsed }, null, 2));
  if (!eff?.status?.success) process.exit(1);
  if (!execute) return null;
  const { signature } = await kp.signTransaction(bytes);
  const res = unwrap(await client.executeTransaction({ transaction: bytes, signatures: [signature], include: { effects: true, objectTypes: true } }));
  const digest = res?.digest;
  recordExecution('testnet', digest);
  const done = unwrap(await client.waitForTransaction({ digest, include: { effects: true, objectTypes: true }, timeout: 60_000 }));
  const types = done?.objectTypes ?? {};
  const changed = (done?.effects?.changedObjects ?? []).map((o: any) => ({ id: o.objectId, op: o.idOperation, out: o.outputState, type: types[o.objectId] ?? null }));
  console.log(JSON.stringify({ digest, status: done?.effects?.status, gasUsed: done?.effects?.gasUsed, changed }, null, 2));
  return { digest, changed, ok: !!done?.effects?.status?.success };
}

if (step === 'publish') {
  const build = JSON.parse(readFileSync(opt('build') ?? '', 'utf8'));
  const tx = new Transaction();
  const cap = tx.publish({ modules: build.modules, dependencies: build.dependencies });
  tx.transferObjects([cap], sender);
  const r = await run(tx, 'publish');
  if (r?.ok) {
    const pkg = r.changed.find((c: any) => c.type === 'package' || c.out === 'PackageWrite')?.id;
    const find = (suffix: string) => r.changed.find((c: any) => typeof c.type === 'string' && c.type.includes(suffix))?.id ?? null;
    const ids = {
      package: pkg,
      registry: find('::passport::AttestorRegistry'),
      admin_cap: find('::passport::AdminCap'),
      publisher: find('::package::Publisher'),
      display: find('::display::Display<'),
      upgrade_cap: find('::package::UpgradeCap'),
      digest: r.digest,
    };
    console.log(JSON.stringify(ids, null, 2));
    writeFileSync(new URL('../../../../../contracts-passport/Published.toml', import.meta.url), `# Generated by publish.ts (TS SDK via Tatum); same layout the Sui CLI writes.
# This file SHOULD be committed to source control

[published.testnet]
chain-id = "4c78adac"
published-at = "${pkg}"
original-id = "${pkg}"
version = 1
toolchain-version = "1.73.0"
build-config = { flavor = "sui", edition = "2024" }
upgrade-capability = "${ids.upgrade_cap}"
`);
  }
} else if (step === 'set-attestor') {
  const pkg = opt('package'), reg = opt('registry'), cap = opt('cap');
  if (!pkg || !reg || !cap) throw new Error('--package, --registry and --cap are required');
  const att = attestorKeypair();
  if (!att) throw new Error('HELIX_ATTESTATION_KEY not set');
  const pk = att.getPublicKey().toRawBytes();
  console.log(`attestor pubkey ${Buffer.from(pk).toString('hex')}`);
  const tx = new Transaction();
  tx.moveCall({ target: `${pkg}::passport::set_attestor`, arguments: [tx.object(cap), tx.object(reg), tx.pure.vector('u8', [...pk])] });
  await run(tx, 'set-attestor');
} else {
  console.error('usage: publish.ts publish --build <json> [--execute] | set-attestor --package --registry --cap [--execute]');
  process.exit(2);
}
