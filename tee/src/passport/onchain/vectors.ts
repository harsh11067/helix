// vectors — deterministic signature test vectors for helix_passport (P4-02).
//
// Fixed seeds → fixed Ed25519 keys → fixed signatures (Ed25519 is deterministic), encoded with the
// SAME `encodeAttestation` the server uses. The rendered Move module is committed at
// contracts-passport/tests/vectors.move and verified on-chain-style inside `sui move test`;
// tee/test/passport-onchain.test.ts checks the committed file is byte-identical to a fresh render.
//
//   cd tee && node src/passport/onchain/vectors.ts --write     # regenerate the Move file

import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { Ed25519Keypair } from '@mysten/sui/keypairs/ed25519';
import { normalizeSuiAddress } from '@mysten/sui/utils';
import { encodeAttestation, type AttestationFields } from './attestation.ts';

export const VECTORS_PATH = new URL('../../../../contracts-passport/tests/vectors.move', import.meta.url);

const seed = (label: string) => createHash('sha256').update(`helix-passport/test-vectors/${label}`).digest();
export const TEST_ATTESTOR = Ed25519Keypair.fromSecretKey(seed('attestor'));
export const TEST_ROGUE = Ed25519Keypair.fromSecretKey(seed('rogue'));

export const ALICE = normalizeSuiAddress('0xa11ce');
export const BOB = normalizeSuiAddress('0xb0b');
export const T0 = 1_700_000_000_000;          // the Move tests set the clock to T0 + 1_000
const NS_ALICE = 'helix-v1-a11cea11cea1';
const NS_BOB = 'helix-v1-b0bb0bb0bb0b';

const base: AttestationFields = {
  owner: ALICE, ns: NS_ALICE, n_settled: 12, wins: 8, brier_bps: 1800, gap_bps: 350, gap_negative: false,
  hidden: 0, badges: 3, issued_ms: T0, expires_ms: T0 + 600_000,
};
/** name → fields. `claim` is calibrated (n 12, Brier 1800); `bob` is not (n 4, Brier 3100). */
export const CASES: Record<string, AttestationFields> = {
  claim: base,
  refresh: { ...base, n_settled: 13, wins: 9, brier_bps: 1700, gap_bps: 300, gap_negative: true, issued_ms: T0 + 60_000, expires_ms: T0 + 660_000 },
  old: { ...base, n_settled: 11, wins: 7, issued_ms: T0 - 60_000 },
  bob: { ...base, owner: BOB, ns: NS_BOB, n_settled: 4, wins: 1, brier_bps: 3100, gap_bps: 2100, hidden: 1, badges: 0 },
  expired: { ...base, issued_ms: T0 - 1_000_000, expires_ms: T0 - 1 },
  other_ns: { ...base, ns: 'helix-v1-000000000000', issued_ms: T0 + 120_000, expires_ms: T0 + 700_000 },
};

const hex = (b: Uint8Array) => Buffer.from(b).toString('hex');

export async function renderMoveVectors(): Promise<string> {
  const out: string[] = [];
  const fn = (name: string, ty: string, body: string) => out.push(`public fun ${name}(): ${ty} { ${body} }`);
  fn('attestor_pubkey', 'vector<u8>', `x"${hex(TEST_ATTESTOR.getPublicKey().toRawBytes())}"`);
  fn('rogue_pubkey', 'vector<u8>', `x"${hex(TEST_ROGUE.getPublicKey().toRawBytes())}"`);
  fn('alice', 'address', `@${ALICE}`);
  fn('bob', 'address', `@${BOB}`);
  fn('t0', 'u64', String(T0));
  for (const [name, f] of Object.entries(CASES)) {
    const payload = encodeAttestation(f);
    fn(`${name}_payload`, 'vector<u8>', `x"${hex(payload)}"`);
    fn(`${name}_sig`, 'vector<u8>', `x"${hex(await TEST_ATTESTOR.sign(payload))}"`);
  }
  // forgery: the claim payload signed by a key the registry does not hold
  fn('rogue_sig', 'vector<u8>', `x"${hex(await TEST_ROGUE.sign(encodeAttestation(CASES.claim)))}"`);
  // a validly signed payload with one trailing byte (the decoder must reject it)
  const trailing = new Uint8Array([...encodeAttestation(CASES.claim), 0]);
  fn('trailing_payload', 'vector<u8>', `x"${hex(trailing)}"`);
  fn('trailing_sig', 'vector<u8>', `x"${hex(await TEST_ATTESTOR.sign(trailing))}"`);
  // the decoded fields the TS encoder put into claim_payload, for the field-by-field Move check
  const c = CASES.claim;
  out.push(`public fun claim_fields(): (address, vector<u8>, u64, u64, u64, u64, bool, u64, u64, u64, u64) {
    (@${normalizeSuiAddress(c.owner)}, b"${c.ns}", ${c.n_settled}, ${c.wins}, ${c.brier_bps}, ${c.gap_bps}, ${c.gap_negative}, ${c.hidden}, ${c.badges}, ${c.issued_ms}, ${c.expires_ms})
}`);
  return `// GENERATED by tee/src/passport/onchain/vectors.ts (fixed seeds). Do not edit by hand.
// Regenerate: cd tee && node src/passport/onchain/vectors.ts --write
// Payloads are BCS(Attestation) from the TypeScript encoder; signatures are raw Ed25519 from
// @mysten/sui's Ed25519Keypair. Verified by passport_tests.move with sui::ed25519.
#[test_only]
module helix_passport::vectors;

${out.join('\n\n')}
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const src = await renderMoveVectors();
  if (process.argv.includes('--write')) { writeFileSync(VECTORS_PATH, src); console.log(`wrote ${VECTORS_PATH.pathname}`); }
  else process.stdout.write(src);
}
